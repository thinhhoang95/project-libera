const PAIRS = mathMarkerPairs({ inlineMathMarkers: "$ $", blockMathMarkers: "$$ $$" });

const PAPER = [
  "# Setup",
  "",
  "**Definition 1.** A function $f$ is *Lipschitz* if $|f(x) - f(y)| \\le L|x - y|$ for all $x, y$.",
  "",
  "We write $\\mathcal{F}_t$ for the filtration generated by the first $t$ rounds.",
  "",
  "Some prose without definitions.",
  "",
  "Let $R_T := \\sum_{t=1}^T \\ell_t$ denote the regret.",
  "",
].join("\n");

function card(overrides: Partial<DefinitionEntry>): DefinitionEntry {
  return { id: "x", kind: "definition", term: "Lipschitz", meaning: "A function whose slope is bounded by $L$.", quote: "is *Lipschitz* if", ...overrides };
}

test("cards are rejected when their math cannot be typeset or sits outside math markers", () => {
  assert.deepEqual(checkMarkdownMath("meaning", "The set $\\{x : x > 0\\}$ of positives.", PAIRS), []);
  assert.match(checkMarkdownMath("meaning", "Bad $\\frac{1}{$ math.", PAIRS).join(), /KaTeX cannot typeset/);
  assert.match(checkMarkdownMath("meaning", "Uses $\\foo x$ here.", PAIRS).join(), /Undefined control sequence|KaTeX cannot typeset/);
  assert.match(checkMarkdownMath("term", "\\mathcal{F}_t", PAIRS).join(), /\\mathcal is outside math markers/);
  assert.match(checkMarkdownMath("meaning", "Open $x + y and never closed.", PAIRS).join(), /never closed/);
  // Code spans are shown as written.
  assert.deepEqual(checkMarkdownMath("meaning", "Typed as `\\R` in the source, it is $\\mathbb{R}$.", PAIRS), []);
});

test("a card's excerpt must be in the document, and settles its line", () => {
  const source = { kind: "text" as const, content: PAPER };
  const good = checkDefinitionCard(card({}), source, PAIRS);
  assert.deepEqual(good.problems, []);
  assert.equal(good.entry.line, 3);

  const missing = checkDefinitionCard(card({ quote: "a function is Lipschitz when", line: 3 }), source, PAIRS);
  assert.match(missing.problems.join(), /is not in the document.*Line 3 reads/);
  assert.match(checkDefinitionCard(card({ quote: undefined, line: 99 }), source, PAIRS).problems.join(), /10 lines; 99 is past its end/);
  assert.match(checkDefinitionCard(card({ quote: undefined }), source, PAIRS).problems.join(), /give a short exact excerpt/);
  assert.match(checkDefinitionCard(card({ meaning: "Lipschitz." }), source, PAIRS).problems.join(), /not just restate it/);
});

test("PDF cards move to the page their excerpt is on", () => {
  const source = { kind: "pdf" as const, pages: [{ pageNumber: 1, text: "Intro" }, { pageNumber: 2, text: "Definition 2.1. A graph is con-\nnected if every pair of vertices is joined." }] };
  const moved = checkDefinitionCard(card({ term: "connected", meaning: "Every two vertices are joined by a path.", quote: "A graph is connected if every pair", page: 1 }), source, PAIRS);
  assert.deepEqual(moved.problems, []);
  assert.equal(moved.entry.page, 2);
  assert.match(moved.notes.join(), /page 2, not 1/);
  assert.match(checkDefinitionCard(card({ quote: undefined, page: 9 }), source, PAIRS).problems.join(), /2 pages; 9 is past its end/);
});

test("passages that look like definitions without a card are found", () => {
  const source = { kind: "text" as const, content: PAPER };
  const uncovered = uncoveredDefinitionPassages(source, [{ ...card({}), line: 3 }]);
  assert.deepEqual(uncovered.map((passage) => passage.line), [5, 9]);
  assert.deepEqual(uncoveredDefinitionPassages(source, [{ ...card({}), line: 3 }, { ...card({}), line: 5 }, { ...card({}), line: 9 }]), []);
});

test("search matches terms, aliases and spelled-out LaTeX", () => {
  const entries = [
    card({ id: "a", kind: "notation", term: "$\\mathcal{F}_t$", meaning: "The filtration up to round $t$.", aliases: ["script F"] }),
    card({ id: "b" }),
  ];
  assert.deepEqual(filterDefinitions(entries, "mathcal").map((entry) => entry.id), ["a"]);
  assert.deepEqual(filterDefinitions(entries, "script f").map((entry) => entry.id), ["a"]);
  assert.deepEqual(filterDefinitions(entries, "", "definition").map((entry) => entry.id), ["b"]);
  assert.deepEqual(findQuoteRange("a  b\nc", "a b c"), { start: 0, end: 6 });
  assert.equal(parseDefinitionsFile({ version: 2, documentPath: "x", entries: [] }), null);
});

async function withLibrary(run: (root: string) => Promise<void>) {
  const directory = await mkdtemp(path.join(os.tmpdir(), "libera-definitions-"));
  const previous = process.env.LIBERA_DATA_DIR;
  process.env.LIBERA_DATA_DIR = directory;
  const root = path.join(directory, "users", "admin");
  try {
    await mkdir(path.join(root, "Research"), { recursive: true });
    await writeFile(path.join(root, "Research", "paper.md"), PAPER);
    await run(root);
  } finally {
    if (previous === undefined) delete process.env.LIBERA_DATA_DIR; else process.env.LIBERA_DATA_DIR = previous;
    await rm(directory, { recursive: true, force: true });
  }
}

function makeContext() {
  const events: AgentEvent[] = [];
  const context: ToolContext = {
    permission: "read-only", skills: AGENT_SKILLS, loadedSkills: new Set([DEFINITIONS_SKILL]), skillState: new Map(),
    notebook: "Research", notebooks: ["Research"], openFiles: new Set(), drafts: new Map(), fileState: new Map(),
    tasks: [], snapshots: new RunSnapshots(`run-${Math.random().toString(36).slice(2, 12)}`), changed: new Map(), maxResultChars: 40_000,
    signal: new AbortController().signal, emit: (event) => events.push(event),
  };
  return { context, events };
}

test("SaveDefinitions saves valid cards, sends invalid ones back, and the finish pass asks for missed passages", async () => {
  await withLibrary(async (root) => {
    const { context, events } = makeContext();
    const save = activeTools(ALL_TOOLS, context).find((tool) => tool.name === "SaveDefinitions")!;
    assert.ok(save, "the skill's tool is offered in Read Only");

    const first = await save.run({ path: "Research/paper.md", entries: [
      { kind: "definition", term: "Lipschitz", meaning: "A function $f$ with $|f(x)-f(y)| \\le L|x-y|$.", quote: "is *Lipschitz* if" },
      { kind: "notation", term: "\\mathcal{F}_t", meaning: "The filtration of the first $t$ rounds.", quote: "We write $\\mathcal{F}_t$ for the filtration" },
    ] }, context);
    assert.equal(first.isError, true);
    assert.match(first.text, /Saved 1 card[\s\S]*1 card was rejected[\s\S]*entries\[1\][\s\S]*outside math markers[\s\S]*Put formulas inside \$…\$/);
    assert.deepEqual(events.filter((event) => event.type === "definitions_saved"), [{ type: "definitions_saved", path: "Research/paper.md", count: 1 }]);

    const skill = AGENT_SKILLS.find((candidate) => candidate.name === DEFINITIONS_SKILL)!;
    const feedback = await skill.finishPass!(context, { final: false });
    assert.match(feedback ?? "", /line 5:[\s\S]*line 9:/);

    const second = await save.run({ path: "Research/paper.md", entries: [
      { kind: "notation", term: "$\\mathcal{F}_t$", meaning: "The filtration of the first $t$ rounds.", quote: "We write $\\mathcal{F}_t$ for the filtration", aliases: ["filtration"] },
      { kind: "notation", term: "$R_T$", meaning: "The regret, $R_T = \\sum_{t=1}^T \\ell_t$.", quote: "denote the regret" },
    ] }, context);
    assert.equal(second.isError, false, second.text);
    const { definitions, stale } = await readDefinitions("Research/paper.md");
    assert.equal(stale, false);
    assert.deepEqual(definitions?.entries.map((entry) => [entry.term, entry.line]), [["Lipschitz", 3], ["$\\mathcal{F}_t$", 5], ["$R_T$", 9]]);
    assert.equal(await skill.finishPass!(context, { final: false }), null);

    // A later run replaces the cards; the document changing makes them stale.
    await writeFile(path.join(root, "Research", "paper.md"), `${PAPER}\nMore.\n`);
    assert.equal((await readDefinitions("Research/paper.md")).stale, true);

    // The side-car follows the document and goes with it.
    await moveFile("Research/paper.md", "Research", "renamed.md");
    assert.equal((await readDefinitions("Research/renamed.md")).definitions?.entries.length, 3);
    await deleteFile("Research/renamed.md");
    await assert.rejects(stat(path.join(root, "Research", ".libera", "definitions", "by-path", "renamed.md.json")));

    await writeFile(path.join(root, "Research", "paper.md"), PAPER);
    await deleteDefinitions("Research/paper.md");
    assert.equal((await readDefinitions("Research/paper.md")).definitions, null);
  });
});
