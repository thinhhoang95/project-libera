/** The list, with the code from Preferences → Speech added when it is not one of them. */
export function transcriptionLanguageChoices(preferred: string) {
  if (!preferred || TRANSCRIPTION_LANGUAGES.some((language) => language.code === preferred)) return TRANSCRIPTION_LANGUAGES;
  return [{ code: preferred, name: preferred.toUpperCase() }, ...TRANSCRIPTION_LANGUAGES];
}
