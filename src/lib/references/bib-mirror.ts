import { createHash, randomUUID } from "node:crypto";
import { readFile, realpath, rename, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { writeJsonAtomically } from "@/lib/storage/fs-utils";
import { filePathFromParts, notebookPath, notebookSystemDirectoryPath, splitFilePath } from "@/lib/storage/paths";
import { serializeBibtex } from "./bibtex";
import type { ReferenceLibrary } from "./types";

// The generated `.bib` mirror for LaTeX projects (docs/references/plan.md
// Phase 5). With the notebook setting `bibMirror` on, `<notebook>/references.bib`
// holds the whole library as BibLaTeX (UTF-8), rewritten after every library
// transaction (debounced, and only when the text changed). LaTeX documents
// in the notebook cite it with `\addbibresource{references.bib}` or
// `\bibliography{references}`; the LaTeX build adds the notebook folder to
// BIBINPUTS so documents in subfolders find it too.
//
// The mirror is never edited by hand on purpose, but a user may do so
// anyway. The hash of the last text Libera wrote is kept in
// `<system dir>/references/bib-mirror.json`; when the file on disk no longer
// has that hash (or a references.bib that Libera did not write is already
// there), it is left alone and the mirror goes to `references.libera.bib`
// instead, with the result reporting `protected`.

export const BIB_MIRROR_FILE = "references.bib";
export const BIB_MIRROR_FALLBACK_FILE = "references.libera.bib";
export const BIB_MIRROR_HEADER = "% Generated by Libera from this notebook's References. Edit references in Libera; changes here are overwritten.";
/** Library changes within this window become one rewrite. */
export const BIB_MIRROR_DEBOUNCE_MS = 1_000;
const STATE_VERSION = 1;

export type BibMirrorResult = {
  /**
   * written: the mirror was (re)written; unchanged: it already had this text;
   * disabled: the setting is off (an existing file is left as it is);
   * protected: references.bib was edited outside Libera, so the mirror was
   * written to references.libera.bib instead.
   */
  status: "written" | "unchanged" | "disabled" | "protected";
  /** Library-relative path of the file that holds the mirror ("Notebook/references.bib"). */
  path: string;
  /** For `protected`: the edited file that was left alone. */
  editedPath?: string;
  entries: number;
};

type MirrorState = { version: number; hash?: string };

function sha256(text: string) {
  return createHash("sha256").update(text, "utf8").digest("hex");
}

export function bibMirrorStatePath(notebook: string) {
  return path.join(notebookSystemDirectoryPath(notebook), "references", "bib-mirror.json");
}

/** The mirror's text: the header, then every entry as BibLaTeX, sorted by key. */
export function renderBibMirror(library: ReferenceLibrary) {
  const entries = Object.values(library.entries).sort((left, right) => left.key.localeCompare(right.key, "en"));
  const body = serializeBibtex(entries, { dialect: "biblatex", includeAliases: true });
  return `${BIB_MIRROR_HEADER}\n\n${body}`;
}

async function readText(target: string) {
  try {
    return await readFile(target, "utf8");
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === "ENOENT") return null;
    throw error;
  }
}

async function readState(notebook: string): Promise<MirrorState> {
  try {
    const state = JSON.parse(await readFile(bibMirrorStatePath(notebook), "utf8")) as MirrorState;
    return state?.version === STATE_VERSION ? state : { version: STATE_VERSION };
  } catch {
    return { version: STATE_VERSION };
  }
}

/** Write next to the target and rename over it, so LaTeX never reads half a file. */
async function writeAtomically(target: string, text: string) {
  const temporary = path.join(path.dirname(target), `.${path.basename(target)}.${randomUUID()}.tmp`);
  try {
    await writeFile(temporary, text, "utf8");
    await rename(temporary, target);
  } finally {
    await rm(temporary, { force: true });
  }
}

async function tetherOwnsMirror(notebook: string, candidates: string[]) {
  const statePath = path.join(notebookSystemDirectoryPath(notebook), "references", "bib-tether.json");
  let text: string;
  try { text = await readFile(statePath, "utf8"); } catch (error) {
    if ((error as NodeJS.ErrnoException).code === "ENOENT") return false;
    throw error;
  }
  try {
    const { target } = JSON.parse(text) as { target: { kind: string; path: string } };
    let absolute = target.path;
    if (target.kind === "notebook") absolute = filePathFromParts(notebook, target.path.split("/"));
    else if (target.kind === "library") {
      const { notebook: owner, pathParts } = splitFilePath(target.path);
      absolute = filePathFromParts(owner, pathParts);
    }
    const identity = await realpath(absolute).catch(() => path.resolve(absolute));
    for (const candidate of candidates) if (identity === await realpath(candidate).catch(() => path.resolve(candidate))) return true;
    return false;
  } catch {
    return true; // Damaged tether history must not authorize a mirror overwrite.
  }
}

/**
 * Bring the notebook's mirror up to date with `library`. Does nothing when
 * the setting is off. Never overwrites a references.bib that was changed
 * outside Libera (see the module comment).
 */
export async function writeBibMirror(notebook: string, library: ReferenceLibrary): Promise<BibMirrorResult> {
  const entries = Object.keys(library.entries).length;
  const mainPath = `${notebook}/${BIB_MIRROR_FILE}`;
  if (!library.settings?.bibMirror) return { status: "disabled", path: mainPath, entries };
  const root = notebookPath(notebook);
  // One owner per output: a tether preserves external edits and custom fields,
  // whereas the generated mirror replaces its entire output.
  if (await tetherOwnsMirror(notebook, [path.join(root, BIB_MIRROR_FILE), path.join(root, BIB_MIRROR_FALLBACK_FILE)])) {
    return { status: "disabled", path: mainPath, entries };
  }
  const text = renderBibMirror(library);
  const hash = sha256(text);
  const state = await readState(notebook);
  const main = path.join(root, BIB_MIRROR_FILE);
  const current = await readText(main);
  const currentHash = current === null ? null : sha256(current);

  if (currentHash === hash) {
    if (state.hash !== hash) await writeJsonAtomically(bibMirrorStatePath(notebook), { version: STATE_VERSION, hash });
    return { status: "unchanged", path: mainPath, entries };
  }
  if (current === null || currentHash === state.hash) {
    await writeAtomically(main, text);
    await writeJsonAtomically(bibMirrorStatePath(notebook), { version: STATE_VERSION, hash });
    return { status: "written", path: mainPath, entries };
  }

  // Edited by hand, or a references.bib Libera never wrote: keep it, mirror beside it.
  const fallback = path.join(root, BIB_MIRROR_FALLBACK_FILE);
  const fallbackPath = `${notebook}/${BIB_MIRROR_FALLBACK_FILE}`;
  if ((await readText(fallback)) !== text) {
    await writeAtomically(fallback, text);
    console.warn(`[references] ${mainPath} was changed outside Libera and was left as it is; the generated bibliography was written to ${fallbackPath}.`);
  }
  return { status: "protected", path: fallbackPath, editedPath: mainPath, entries };
}

// ---------------------------------------------------------------------------
// Regenerating after library transactions
// ---------------------------------------------------------------------------

type Scheduler = {
  timers: Map<string, ReturnType<typeof setTimeout>>;
  pending: Map<string, ReferenceLibrary>;
  chains: Map<string, Promise<BibMirrorResult | null>>;
  results: Map<string, BibMirrorResult>;
};

const SCHEDULER_KEY = Symbol.for("libera.referenceBibMirror");
const holder = globalThis as { [SCHEDULER_KEY]?: Scheduler };
const scheduler = holder[SCHEDULER_KEY] ??= { timers: new Map(), pending: new Map(), chains: new Map(), results: new Map() };

/** Write the notebook's pending library now (after earlier writes). Resolves with the result, or null when nothing was pending. */
export function flushBibMirror(notebook: string): Promise<BibMirrorResult | null> {
  clearTimeout(scheduler.timers.get(notebook));
  scheduler.timers.delete(notebook);
  const library = scheduler.pending.get(notebook);
  scheduler.pending.delete(notebook);
  const previous = scheduler.chains.get(notebook) ?? Promise.resolve(null);
  if (!library) return previous.catch(() => null);
  const next = previous.catch(() => null).then(async () => {
    try {
      const result = await writeBibMirror(notebook, library);
      scheduler.results.set(notebook, result);
      return result;
    } catch (error) {
      console.error(`[references] Could not write the .bib mirror of ${notebook}:`, error);
      return null;
    }
  });
  scheduler.chains.set(notebook, next);
  void next.finally(() => { if (scheduler.chains.get(notebook) === next) scheduler.chains.delete(notebook); });
  return next;
}

/** Regenerate the mirror from `library` now, after any write in progress (replaces a pending regeneration). */
export async function regenerateBibMirror(notebook: string, library: ReferenceLibrary): Promise<BibMirrorResult> {
  scheduler.pending.set(notebook, library);
  const result = await flushBibMirror(notebook);
  if (!result) throw new Error("The .bib mirror could not be written.");
  return result;
}

/**
 * A library transaction committed: regenerate the mirror after
 * BIB_MIRROR_DEBOUNCE_MS when the setting is on. Cheap when it is off.
 * Never throws.
 */
export function scheduleBibMirror(notebook: string, library: ReferenceLibrary, debounceMs = BIB_MIRROR_DEBOUNCE_MS) {
  if (!library.settings?.bibMirror && !scheduler.pending.has(notebook)) return;
  scheduler.pending.set(notebook, library);
  clearTimeout(scheduler.timers.get(notebook));
  const timer = setTimeout(() => void flushBibMirror(notebook), debounceMs);
  timer.unref?.();
  scheduler.timers.set(notebook, timer);
}

/** The last result of a regeneration, if any ran in this process. */
export function lastBibMirrorResult(notebook: string) {
  return scheduler.results.get(notebook);
}

/** Drop pending regenerations (tests, before the data directory changes). */
export function resetBibMirrorScheduler() {
  for (const timer of scheduler.timers.values()) clearTimeout(timer);
  scheduler.timers.clear();
  scheduler.pending.clear();
  scheduler.results.clear();
}
